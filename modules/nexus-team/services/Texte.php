    public static function sprache(): string
    {
        $code = strtolower(explode('-', (string)Yii::$app->language)[0]);
        return isset(self::T[$code]) ? $code : 'en';
    }

    public static function t(string $schluessel, ?string $sprache = null): string
    {
        $s = $sprache ?? self::sprache();
        return self::T[$s][$schluessel] ?? self::T['en'][$schluessel] ?? $schluessel;
    }

    /** Willkommenstext in der Sprache des Mitglieds ("en-US" -> "en"); unbekannte Sprachen bekommen Englisch. */
    public static function willkommen(?string $mitgliedsSprache, string $name, string $ich): string
    {
        $code = strtolower(explode('-', (string)$mitgliedsSprache)[0]);
        $text = self::WILLKOMMEN[$code] ?? self::WILLKOMMEN['en'];
        return strtr($text, ['{name}' => $name, '{ich}' => $ich]);
    }
